import os
import json
import torch
import glob
import numpy as np
import matplotlib.pyplot as plt
from pathlib import Path

from fdtd_em.config import generation_config as cfg
from fdtd_em.train.model import ConditionalDDPM
from fdtd_em.train.dataset import MyDataset


def find_latest_file(folder, extension=""):
    files = glob.glob(os.path.join(folder, f"*{extension}"))
    if not files: return None
    return sorted(files)[-1]


def load_field_stats(dataset_root):
    stats_path = os.path.join(dataset_root, "field_stats.json")
    if os.path.exists(stats_path):
        with open(stats_path, 'r') as f:
            stats = json.load(f)
        return stats['min'], stats['max']
    return -1.0, 1.0


def main():
    device = "cuda" if torch.cuda.is_available() else "cpu"
    print(f" 启动逆向设计可视化脚本 (设备: {device})")

    # 1. 加载模型
    latest_model_path = find_latest_file("checkpoints", "diffusion_model_*.pth")
    if not latest_model_path:
        print("！！！ 找不到模型权重！")
        return

    # 注意：这里的 target_dim 取决于你的逆向目标。如果是生成结构，通道数是1。
    model = ConditionalDDPM(target_dim=1, n_steps=cfg.diffusion_steps, device=device)
    model.load_state_dict(torch.load(latest_model_path, map_location=device, weights_only=True))
    model.to(device)
    model.eval()

    # 2. 获取数据与统计量
    latest_dataset_run = find_latest_file("dataset")
    samples_dir = os.path.join(latest_dataset_run, "samples")
    train_files = [p for p in Path(samples_dir).iterdir() if p.is_dir()]

    f_min, f_max = load_field_stats(latest_dataset_run)
    dataset = MyDataset(train_files)

    # 抽取样本 (匹配新版 Dataset 输出顺序)
    field_map, real_structure, phys_cond = dataset[0]

    # 扩充维度以适配批处理 [B, C, H, W]
    field_map_cond = field_map.unsqueeze(0).to(device)
    phys_cond = phys_cond.unsqueeze(0).to(device)

    # 3. 运行扩散模型逆向采样 (输入目标场图，生成结构图)
    print(" 正在运行 DDPM 逆向推演结构，请稍候...")
    with torch.no_grad():
        # 注意：这里假设你的 model.sample 支持同时输入 img_cond 和 phys_cond 进行逆向
        predicted_structure = model.sample(img_cond=field_map_cond, phys_cond=phys_cond)

    # 4. 数据反归一化
    # 将模型输出的 [-1, 1] 结构图还原为真实介电常数 (1.0 到 eps_r_max)
    def denorm_eps(tensor):
        return (tensor.squeeze().cpu().numpy() + 1.0) / 2.0 * (cfg.eps_r_max - 1.0) + 1.0

    real_eps_map = denorm_eps(real_structure)
    pred_eps_map = denorm_eps(predicted_structure)

    # 将输入的目标场图还原为物理场强
    target_field_phys = (field_map[0].numpy() + 1.0) / 2.0 * (f_max - f_min) + f_min

    # 5. ================= 绘制对比大图 =================
    print(" 正在绘制可视化对比图...")
    fig, axes = plt.subplots(1, 3, figsize=(16, 5))

    # [图 1]：模型输入的条件 (Target Field Map - 取透射通道)
    ax1 = axes[0]
    im1 = ax1.imshow(target_field_phys, cmap='viridis', origin='lower')
    ax1.set_title("Input Target\n(Desired 2D Field Map)", fontsize=14, fontweight='bold')
    ax1.set_xlabel("Z-axis grid")
    ax1.set_ylabel("Y-axis grid")
    fig.colorbar(im1, ax=ax1, fraction=0.046, pad=0.04, label="Electric Field (V/m)")

    # [图 2]：真实的物理结构 (Ground Truth)
    ax2 = axes[1]
    im2 = ax2.imshow(real_eps_map, cmap='plasma', origin='lower', vmin=1.0, vmax=cfg.eps_r_max)
    ax2.set_title("Ground Truth Structure\n(FDTD Simulation Target)", fontsize=12, color='green')
    fig.colorbar(im2, ax=ax2, fraction=0.046, pad=0.04, label="Relative Permittivity (eps_r)")

    # [图 3]：扩散模型逆向预测的物理结构 (Predicted)
    ax3 = axes[2]
    im3 = ax3.imshow(pred_eps_map, cmap='plasma', origin='lower', vmin=1.0, vmax=cfg.eps_r_max)
    ax3.set_title("AI Inverse Designed Structure\n(Generated by DDPM)", fontsize=12, color='darkred')
    fig.colorbar(im3, ax=ax3, fraction=0.046, pad=0.04, label="Relative Permittivity (eps_r)")

    plt.tight_layout()
    save_path = "diffusion_inverse_design_result.png"
    plt.savefig(save_path, dpi=300, bbox_inches='tight')
    print(f" 可视化图像已保存至项目根目录的: {save_path}")


if __name__ == "__main__":
    main()
